#!/usr/bin/env python3
"""Auto-generate sitemap.xml for the Digital Dokan website.

Scans the repo root for .html pages and rebuilds sitemap.xml.
Run by .github/workflows/sitemap.yml on every push that touches an
.html file, so a newly published page appears in the sitemap on its own.
App / private / verification files are excluded on purpose.
"""
import glob
import re
import subprocess
import sys
from datetime import date

BASE = "https://digitaldokanapp.github.io/digital-dokan/"

# Known pages, in sitemap order: filename -> (changefreq, priority)
KNOWN = [
    ("index.html",    "daily",   "1.0"),
    ("features.html", "weekly",  "0.9"),
    ("pricing.html",  "weekly",  "0.8"),
    ("compare.html",  "monthly", "0.7"),
    ("about.html",    "monthly", "0.6"),
    ("contact.html",  "monthly", "0.6"),
    ("privacy.html",  "yearly",  "0.3"),
    ("terms.html",    "yearly",  "0.3"),
    ("blog.html",     "weekly",  "0.5"),
]

# Never list these in the sitemap (the app, the admin panel, the public
# khata page, and Google's verification file).
EXCLUDE = {"mydokan2.html", "admin.html", "khata.html", "website-builder.html"}
EXCLUDE_RE = re.compile(r"^google[0-9a-f]+\.html$")

# Any other .html file is treated as a blog article.
ARTICLE_FREQ, ARTICLE_PRIORITY = "monthly", "0.7"


def lastmod(filename):
    """Date of the file's last git commit (YYYY-MM-DD), else today."""
    try:
        out = subprocess.run(
            ["git", "log", "-1", "--format=%cs", "--", filename],
            capture_output=True, text=True, timeout=15,
        ).stdout.strip()
        if re.fullmatch(r"\d{4}-\d{2}-\d{2}", out):
            return out
    except Exception:
        pass
    return date.today().isoformat()


def main():
    files = {f.split("/")[-1] for f in glob.glob("*.html")}
    entries = []  # (loc, lastmod, changefreq, priority)

    for name, freq, prio in KNOWN:
        if name in files:
            loc = BASE if name == "index.html" else BASE + name
            entries.append((loc, lastmod(name), freq, prio))
            files.discard(name)

    for name in sorted(files):
        if name in EXCLUDE or EXCLUDE_RE.match(name):
            continue
        entries.append((BASE + name, lastmod(name), ARTICLE_FREQ, ARTICLE_PRIORITY))

    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        "<!-- Auto-generated by generate_sitemap.py - do not edit by hand -->",
        '<urlset xmlns="http://www.sitemap.org/schemas/sitemap/0.9">',
        "",
    ]
    for loc, mod, freq, prio in entries:
        lines += [
            "  <url>",
            f"    <loc>{loc}</loc>",
            f"    <lastmod>{mod}</lastmod>",
            f"    <changefreq>{freq}</changefreq>",
            f"    <priority>{prio}</priority>",
            "  </url>",
            "",
        ]
    lines.append("</urlset>")

    with open("sitemap.xml", "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"sitemap.xml written with {len(entries)} URLs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
